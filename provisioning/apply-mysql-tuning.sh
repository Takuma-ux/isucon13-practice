#!/usr/bin/env bash
# Write isucon-tuning.cnf from /proc/meminfo and restart MySQL. Sourced or run standalone.
#
# SAFETY: Sizes InnoDB from *this host's* MemTotal. Run ONLY on the competition EC2
# app server — never on a developer laptop. Wrong-host runs can allocate tens of GiB
# to MySQL and destabilize the machine.
#
# Requires CONFIRM_MYSQL_TUNING=yes (non-interactive) or typing "yes" at the prompt.
# Dry-run (no write, no restart): MYSQL_TUNING_DRY_RUN=1
set -euo pipefail

compute_mysql_pool_mb() {
	mem_kb="$(awk '/^MemTotal:/ {print $2; exit}' /proc/meminfo)"
	# ~45% of RAM for InnoDB on a shared ISUCON13 node; round down to 128MiB steps.
	local pool_mb="$((mem_kb * 45 / 100 / 1024))"
	pool_mb="$((pool_mb / 128 * 128))"
	if [[ "$pool_mb" -lt 128 ]]; then
		pool_mb=128
	fi
	echo "$mem_kb $pool_mb"
}

require_mysql_tuning_confirmation() {
	local mem_kb="$1"
	local pool_mb="$2"
	local mem_gib
	mem_gib="$(awk -v k="$mem_kb" 'BEGIN { printf "%.1f", k/1024/1024 }')"

	echo ""
	echo "================================================================================"
	echo " WARNING: MySQL InnoDB buffer pool tuning uses THIS machine's RAM"
	echo "================================================================================"
	echo "  Host MemTotal:     ${mem_kb} kB (~${mem_gib} GiB)"
	echo "  Requested in cnf:  innodb_buffer_pool_size = ${pool_mb}M"
	echo "  (InnoDB may round up further to chunk_size × instances.)"
	echo ""
	echo "  Run this ONLY on the real ISUCON deployment host (competition EC2)."
	echo "  Do NOT run on a local dev laptop — server-scale values can exhaust RAM"
	echo "  and crash unrelated processes."
	echo "================================================================================"
	echo ""

	if [[ "${MYSQL_TUNING_DRY_RUN:-}" == "1" ]]; then
		echo "MYSQL_TUNING_DRY_RUN=1: will not write config or restart MySQL."
		return 0
	fi

	if [[ "${CONFIRM_MYSQL_TUNING:-}" == "yes" ]]; then
		return 0
	fi

	if [[ -t 0 ]]; then
		read -r -p "Type 'yes' to write /etc/mysql/.../isucon-tuning.cnf and restart MySQL on THIS host: " ans
		if [[ "$ans" == "yes" ]]; then
			return 0
		fi
		echo "Aborted (confirmation not given)." >&2
		exit 1
	fi

	echo "Aborted: set CONFIRM_MYSQL_TUNING=yes to proceed in non-interactive mode." >&2
	exit 1
}

apply_mysql_tuning() {
	read -r mem_kb pool_mb < <(compute_mysql_pool_mb)
	require_mysql_tuning_confirmation "$mem_kb" "$pool_mb"

	mysql_dropin=/etc/mysql/mysql.conf.d/isucon-tuning.cnf
	local cnf_body
	cnf_body="# Generated by provisioning/apply-mysql-tuning.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# MemTotal=${mem_kb}kB shared-host policy -> innodb_buffer_pool_size=${pool_mb}M

[mysqld]
skip_name_resolve = 1
max_connections = 500
innodb_buffer_pool_size = ${pool_mb}M
"

	if [[ "${MYSQL_TUNING_DRY_RUN:-}" == "1" ]]; then
		echo "--- Would write to ${mysql_dropin} ---"
		printf '%s' "$cnf_body"
		echo "--- end dry-run ---"
		return 0
	fi

	install -D -m 0644 /dev/null "$mysql_dropin"
	printf '%s' "$cnf_body" >"$mysql_dropin"
	echo "Wrote $mysql_dropin (innodb_buffer_pool_size=${pool_mb}M from MemTotal=${mem_kb}kB)"
	if systemctl is-active --quiet mysql 2>/dev/null || systemctl is-active --quiet mysqld 2>/dev/null; then
		echo "Restarting MySQL to pick up buffer pool..."
		systemctl restart mysql 2>/dev/null || systemctl restart mysqld 2>/dev/null || {
			echo "Could not restart mysql — restart manually" >&2
			return 1
		}
	fi
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
	if [[ "${EUID:-$(id -u)}" -ne 0 ]]; then
		echo "Run as root: sudo CONFIRM_MYSQL_TUNING=yes $0" >&2
		echo "Or: sudo MYSQL_TUNING_DRY_RUN=1 $0   # preview only, no restart" >&2
		exit 1
	fi
	apply_mysql_tuning
fi
