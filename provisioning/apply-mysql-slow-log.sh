#!/usr/bin/env bash
# Enable or disable MySQL slow query log for a diagnostic bench run (pt-query-digest).
#
# NOT for permanent use — slow_query_log adds I/O overhead.
#
# Enable (writes drop-in + restarts MySQL):
#   sudo CONFIRM_SLOW_LOG=yes ./provisioning/apply-mysql-slow-log.sh on
# Disable (removes drop-in + restarts MySQL):
#   sudo CONFIRM_SLOW_LOG=yes ./provisioning/apply-mysql-slow-log.sh off
#
# Preview only (no write, no restart):
#   sudo MYSQL_SLOW_LOG_DRY_RUN=1 ./provisioning/apply-mysql-slow-log.sh on|off
#
# After a bench run, analyze:
#   sudo pt-query-digest /var/log/mysql/isucon-slow.log
set -euo pipefail

SLOW_LOG_DROPIN=/etc/mysql/mysql.conf.d/isucon-slow-log.cnf
SLOW_LOG_FILE=/var/log/mysql/isucon-slow.log
LONG_QUERY_TIME=0.05

usage() {
	echo "usage: CONFIRM_SLOW_LOG=yes $0 on|off" >&2
	echo "       MYSQL_SLOW_LOG_DRY_RUN=1 $0 on|off   # preview" >&2
	exit 2
}

require_confirmation() {
	if [[ "${MYSQL_SLOW_LOG_DRY_RUN:-}" == "1" ]]; then
		echo "MYSQL_SLOW_LOG_DRY_RUN=1: will not write config or restart MySQL."
		return 0
	fi
	if [[ "${CONFIRM_SLOW_LOG:-}" == "yes" ]]; then
		return 0
	fi
	echo "Aborted: set CONFIRM_SLOW_LOG=yes (diagnostic bench only, restarts MySQL)." >&2
	exit 1
}

restart_mysql_if_active() {
	if [[ "${MYSQL_SLOW_LOG_DRY_RUN:-}" == "1" ]]; then
		echo "[dry-run] Would restart MySQL."
		return 0
	fi
	if systemctl is-active --quiet mysql 2>/dev/null || systemctl is-active --quiet mysqld 2>/dev/null; then
		echo "Restarting MySQL to apply slow log settings..."
		systemctl restart mysql 2>/dev/null || systemctl restart mysqld
	fi
}

slow_log_on() {
	require_confirmation
	local cnf_body
	cnf_body="# Generated by provisioning/apply-mysql-slow-log.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Diagnostic bench only — remove with: CONFIRM_SLOW_LOG=yes $0 off

[mysqld]
slow_query_log = 1
long_query_time = ${LONG_QUERY_TIME}
slow_query_log_file = ${SLOW_LOG_FILE}
log_slow_extra = 1
"

	if [[ "${MYSQL_SLOW_LOG_DRY_RUN:-}" == "1" ]]; then
		echo "--- Would write ${SLOW_LOG_DROPIN} ---"
		printf '%s' "$cnf_body"
		echo "--- Would ensure log dir and touch ${SLOW_LOG_FILE} (mysql:adm) ---"
		echo "--- end dry-run ---"
		return 0
	fi

	install -d -m 0755 -o mysql -g adm /var/log/mysql
	install -m 0640 /dev/null "$SLOW_LOG_FILE"
	chown mysql:adm "$SLOW_LOG_FILE"
	install -D -m 0644 /dev/null "$SLOW_LOG_DROPIN"
	printf '%s' "$cnf_body" >"$SLOW_LOG_DROPIN"
	echo "Wrote $SLOW_LOG_DROPIN (long_query_time=${LONG_QUERY_TIME}s -> $SLOW_LOG_FILE)"
	restart_mysql_if_active
	echo "Analyze after bench: sudo pt-query-digest $SLOW_LOG_FILE"
}

slow_log_off() {
	require_confirmation
	if [[ "${MYSQL_SLOW_LOG_DRY_RUN:-}" == "1" ]]; then
		echo "[dry-run] Would remove $SLOW_LOG_DROPIN and restart MySQL."
		return 0
	fi
	if [[ -f "$SLOW_LOG_DROPIN" ]]; then
		rm -f "$SLOW_LOG_DROPIN"
		echo "Removed $SLOW_LOG_DROPIN (slow log disabled)."
	else
		echo "No $SLOW_LOG_DROPIN — already off."
	fi
	restart_mysql_if_active
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
	if [[ "${EUID:-$(id -u)}" -ne 0 ]]; then
		echo "Run as root: sudo CONFIRM_SLOW_LOG=yes $0 on|off" >&2
		exit 1
	fi
	case "${1:-}" in
	on | enable) slow_log_on ;;
	off | disable) slow_log_off ;;
	*) usage ;;
	esac
fi
